import { Accordion, Alert, Anchor, Badge, Code, Group, Loader, Modal, Stack, Tabs, Text, TextInput } from '@mantine/core';
import { IconAlertTriangle, IconSearch } from '@tabler/icons-react';
import { useMemo, useState } from 'react';
import type { UseQueryResult } from '@tanstack/react-query';
import { useBackendThirdPartyLicenses, useFrontendThirdPartyLicenses } from '../api/queries';
import type { ThirdPartyLicenses, ThirdPartyPackage } from '../api/types';

interface ThirdPartyLicensesModalProps {
  opened: boolean;
  onClose: () => void;
}

/**
 * Help ▸ About ▸ Third-party licences: the npm packages of the frontend
 * bundle (list generated at build time) and the Python packages of the
 * backend (read from the installed environment), with their licence texts.
 */
export function ThirdPartyLicensesModal({ opened, onClose }: ThirdPartyLicensesModalProps) {
  const frontend = useFrontendThirdPartyLicenses(opened);
  const backend = useBackendThirdPartyLicenses(opened);
  const [filter, setFilter] = useState('');

  return (
    <Modal opened={opened} onClose={onClose} title="Third-party licences" size="xl" centered>
      <Stack gap="sm">
        <Text size="sm">
          ReqManTool uses the following open-source packages. Each keeps its own licence; the texts below are copied
          from the packages.
        </Text>
        <TextInput
          placeholder="Filter by package or licence"
          leftSection={<IconSearch size={14} />}
          value={filter}
          onChange={(event) => setFilter(event.currentTarget.value)}
          aria-label="Filter packages"
        />
        <Tabs defaultValue="frontend" keepMounted={false}>
          <Tabs.List>
            <Tabs.Tab value="frontend">Frontend (npm){countLabel(frontend)}</Tabs.Tab>
            <Tabs.Tab value="backend">Backend (Python){countLabel(backend)}</Tabs.Tab>
          </Tabs.List>
          <Tabs.Panel value="frontend" pt="sm">
            <PackageList
              query={frontend}
              filter={filter}
              unavailable="The licence list is generated by the frontend build (npm run build) and was not found next to this page."
            />
          </Tabs.Panel>
          <Tabs.Panel value="backend" pt="sm">
            <PackageList query={backend} filter={filter} unavailable="The backend could not list its packages." />
          </Tabs.Panel>
        </Tabs>
      </Stack>
    </Modal>
  );
}

function countLabel(query: UseQueryResult<ThirdPartyLicenses>): string {
  return query.data ? ` · ${query.data.packages.length}` : '';
}

function matches(pkg: ThirdPartyPackage, filter: string): boolean {
  const needle = filter.trim().toLowerCase();
  return !needle || pkg.name.toLowerCase().includes(needle) || pkg.license.toLowerCase().includes(needle);
}

function PackageList({
  query,
  filter,
  unavailable,
}: {
  query: UseQueryResult<ThirdPartyLicenses>;
  filter: string;
  unavailable: string;
}) {
  const packages = useMemo(
    () => (query.data?.packages ?? []).filter((pkg) => matches(pkg, filter)),
    [query.data, filter],
  );

  if (query.isLoading) return <Loader size="sm" />;
  if (query.isError) {
    return (
      <Alert color="orange" icon={<IconAlertTriangle size={16} />} title="Licence list unavailable">
        {unavailable} ({query.error.message})
      </Alert>
    );
  }
  if (!query.data || query.data.packages.length === 0) {
    return (
      <Text size="sm" c="dimmed">
        No third-party packages listed.
      </Text>
    );
  }
  if (packages.length === 0) {
    return (
      <Text size="sm" c="dimmed">
        No package matches the filter.
      </Text>
    );
  }
  return (
    <Accordion variant="contained" chevronPosition="left">
      {packages.map((pkg) => (
        <Accordion.Item key={`${pkg.name}@${pkg.version}`} value={`${pkg.name}@${pkg.version}`}>
          <Accordion.Control>
            <Group gap="xs" wrap="nowrap" justify="space-between">
              <Text size="sm">
                {pkg.name} <Text span c="dimmed" size="xs">{pkg.version}</Text>
              </Text>
              <Badge variant="light" size="sm" style={{ textTransform: 'none' }}>
                {pkg.license}
              </Badge>
            </Group>
          </Accordion.Control>
          <Accordion.Panel>
            <Stack gap="xs">
              {pkg.homepage && (
                <Anchor size="sm" href={pkg.homepage} target="_blank" rel="noopener noreferrer">
                  {pkg.homepage}
                </Anchor>
              )}
              {pkg.license_text ? (
                <Code block style={{ whiteSpace: 'pre-wrap', maxHeight: 300, overflow: 'auto' }}>
                  {pkg.license_text}
                </Code>
              ) : (
                <Text size="sm" c="dimmed">
                  The package ships no licence file; its declared licence is {pkg.license}.
                </Text>
              )}
            </Stack>
          </Accordion.Panel>
        </Accordion.Item>
      ))}
    </Accordion>
  );
}
